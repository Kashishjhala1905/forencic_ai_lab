def _font(size):
    for name in ("DejaVuSans.ttf", "arial.ttf", "Arial.ttf", "LiberationSans-Regular.ttf"):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default(size=size)


def render_png(lines, w=1240, h=1000) -> Image.Image:
    img = Image.new("RGB", (w, h), "white")
    d = ImageDraw.Draw(img)
    f, small = _font(34), _font(18)
    y = 60
    for ln in lines:
        d.text((70, y), ln, fill="black", font=f); y += 70
    d.text((70, h - 50), WATERMARK, fill=(150, 150, 150), font=small)
    return img


def render_pdf(lines, path: Path, producer="Forensic AI Lab synthetic generator"):
    c = canvas.Canvas(str(path), pagesize=A4)
    c.setTitle("synthetic"); c.setProducer(producer); c.setCreator(producer)
    y = 780
    for i, ln in enumerate(lines):
        c.setFont("Helvetica-Bold" if i == 0 else "Helvetica", 14); c.drawString(60, y, ln); y -= 30
    c.setFont("Helvetica", 8); c.setFillGray(0.5); c.drawString(60, 40, WATERMARK)
    c.save()


def _scan(splice: bool, seed: int = 1, sigma: float = 5.0, quality: int = 85) -> bytes:
    """Simulated paper scan: document render + Gaussian sensor noise, saved as JPEG.
    If `splice`, a noise-free digitally rendered patch is pasted over the total before saving."""
    import numpy as np
    base = np.asarray(render_png(INVOICE_OK)).astype(float)
    base = base + np.random.default_rng(seed).normal(0, sigma, base.shape)
    img = Image.fromarray(np.clip(base, 0, 255).astype("uint8"))
    if splice:
        img.paste(render_png(["Total Amount: 9180.00"], 640, 80), (60, 680))
    out = io.BytesIO(); img.save(out, "JPEG", quality=quality); return out.getvalue()


def clean_jpeg(quality=85, seed=1) -> bytes:
    return _scan(False, seed=seed, quality=quality)


def spliced_jpeg(seed=1) -> bytes:
    return _scan(True, seed=seed)


